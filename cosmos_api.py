"""V12: museum time river, provenance-aware *suggestions*, private world atlas.

Claims are never re-labelled as facts. Relationships generated by shared metadata
are just search hints. All SQL obeys the existing public/owner authorization rule.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from urllib.parse import urlsplit

from fastapi import Depends, Query

ERA_GROUPS = (
    ('亿年前', '深时与地球', '地质、恒星与古老生命的尺度'),
    ('百万年前', '生命演化', '化石、生物与古生态'),
    ('远古与史前', '漫长史前', '早期人类与环境'),
    ('千年至万年前', '文明起源', '遗址、器物与早期人类活动'),
    ('近千年', '历史文明', '古画、珠宝与历史文物'),
    ('近现代', '工业与现代', '技术、文化与设计的变迁'),
    ('近30年', '数字时代', '数码产品、互联网与游戏'),
    ('最近一年', '正在改变的世界', '新技术、新作品、新奇发现'),
    ('此刻/实时', '当下', '当前事件与实时更新的展品'),
    ('跨越多个时期', '跨越年代', '长期演变、多个时期的共同主题'),
    ('时间不详', '等待考证', '保留未知，不为填空猜测年代'),
)
TIME_IDS = tuple(x[0] for x in ERA_GROUPS)
MAX_RESULTS = 150


def textval(row, key, default=''):
    try:
        val = row[key]
    except (IndexError, KeyError):
        return default
    return val if val is not None else default


def safe_node(row):
    """Expose only the minimal metadata required by exploration UIs."""
    return {
        'id': row['id'], 'title': row['title'], 'category': row['category'],
        'domain': textval(row, 'domain', '其他') or '其他',
        'series': textval(row, 'series', '民间奇趣') or '民间奇趣',
        'time_bucket': textval(row, 'time_bucket', '时间不详') or '时间不详',
        'time_basis': textval(row, 'time_basis', '不详') or '不详',
        'time_note': textval(row, 'time_note', ''),
        'created_at': row['created_at'],
        'source_url': row['source_url'],
        'visibility': row['visibility'],
        'tags': [v.strip() for v in (row['tags'] if isinstance(row['tags'], list) else row['tags'].split(',')) if v.strip()][:12],
        'owner': textval(row, 'owner', ''),
        'image_url': row['image_url'],
    }


def source_host(value):
    """Domain matching is only a weak search hint, never independent verification."""
    if not value:
        return ''
    try:
        parsed = urlsplit(value)
        if parsed.scheme not in ('https', 'http') or not parsed.hostname:
            return ''
        return parsed.hostname.removeprefix('www.').casefold()
    except ValueError:
        return ''


def compare(a, b):
    evidence = []
    def add(kind, label, weight):
        evidence.append({'kind': kind, 'label': label, 'weight': weight})
    common = sorted(set(a['tags']) & set(b['tags']))[:3]
    if common:
        add('shared_tags', '共同标签：' + '、'.join(common), min(15, len(common) * 5))
    if a['category'] != '其他' and a['category'] == b['category']:
        add('same_category', '细分类别相同：' + a['category'], 7)
    if a['domain'] != '其他' and a['domain'] == b['domain']:
        add('same_domain', '主要领域相同：' + a['domain'], 3)
    if a['time_bucket'] not in ('时间不详', '跨越多个时期') and a['time_bucket'] == b['time_bucket']:
        add('same_era', '时间尺度相同：' + a['time_bucket'], 2)
    host_a, host_b = source_host(a['source_url']), source_host(b['source_url'])
    if host_a and host_b and host_a == host_b:
        add('same_host', '原始链接来自同一网站：' + host_a + '（不表示内容被证实）', 2)
    # Do not recommend based only on broad era or source host.
    if not any(x['kind'] in ('shared_tags','same_category','same_domain') for x in evidence):
        return None
    return {'evidence': evidence, 'score': sum(x['weight'] for x in evidence)}


def mount_cosmos(app, db, read_exhibit, maybe_user, require_user, now, fail):
    @app.get('/api/cosmos/eras')
    def time_river(series: str = Query('全部', max_length=24), domain: str = Query('全部', max_length=48),
                   scope: str = Query('public', pattern='^(public|mine)$'), user=Depends(maybe_user)):
        if scope == 'mine' and not user:
            fail(401, '个人时间长河需要登录')
        if series not in ('全部', '藏品系列', '民间奇趣'):
            fail(400, '未知内容系列')
        try:
            from taxonomy import DOMAINS
            if domain != '全部' and domain not in DOMAINS:
                fail(400, '未知领域分类')
        except ImportError:
            pass
        cond = ["e.visibility='public'" if scope == 'public' else 'e.user_id=?']
        args = [] if scope == 'public' else [user['id']]
        if series != '全部':
            cond.append('e.series=?'); args.append(series)
        if domain != '全部':
            cond.append('e.domain=?'); args.append(domain)
        where = ' AND '.join(cond)
        with db() as c:
            # aggregate all visible records; sample is separately bounded
            counts = dict(c.execute('SELECT e.time_bucket,COUNT(*) FROM exhibits e WHERE ' + where + ' GROUP BY e.time_bucket', args).fetchall())
            grouped = defaultdict(list)
            # Per-era bounded sampling prevents recent memes from hiding ancient works.
            for bucket in TIME_IDS:
                rows = c.execute('''SELECT e.*,u.username owner FROM exhibits e
                    JOIN users u ON u.id=e.user_id WHERE ''' + where +
                    ' AND e.time_bucket=? ORDER BY e.created_at DESC,e.id DESC LIMIT 20', (*args, bucket)).fetchall()
                grouped[bucket] = [safe_node(x) for x in rows]
        eras = [{'id': key, 'title': title, 'intro': intro, 'count': int(counts.get(key, 0)),
                 'items': grouped[key][:20]} for key,title,intro in ERA_GROUPS]
        return {'eras': eras, 'scope': scope, 'series': series, 'domain': domain,
                'total': sum(counts.values()), 'sample_limit_per_era': 20,
                'notice': '时代是宽泛筛选标签。作品制作、发现、走红和发布年代不能混为一谈；没有记录的历史内容不会被虚构。'}

    @app.get('/api/cosmos/relations/{exhibit_id}')
    def evidence_relations(exhibit_id: int, limit: int = Query(12, ge=1, le=24), user=Depends(maybe_user)):
        viewer = user['id'] if user else -1
        with db() as c:
            start = read_exhibit(c, exhibit_id, user)
            focal = safe_node(start)
            candidates = c.execute('''SELECT e.*,u.username owner FROM exhibits e
                JOIN users u ON u.id=e.user_id
                WHERE e.id != ? AND (e.visibility='public' OR e.user_id=?)
                ORDER BY e.created_at DESC,e.id DESC LIMIT 1000''', (exhibit_id, viewer)).fetchall()
            # Human links have independent provenance from algorithmic suggestions.
            curated = c.execute('''SELECT l.id,l.from_id,l.to_id,l.kind,l.explanation,l.created_at,
                u.username author,e.id target_id,e.title target_title,e.visibility target_visibility,e.user_id target_owner
                FROM exhibit_links l
                JOIN users u ON u.id=l.author_id
                JOIN exhibits e ON e.id=(CASE WHEN l.from_id=? THEN l.to_id ELSE l.from_id END)
                WHERE (l.from_id=? OR l.to_id=?) AND (e.visibility='public' OR e.user_id=?)
                ORDER BY l.id DESC LIMIT 48''', (exhibit_id, exhibit_id, exhibit_id, viewer)).fetchall()
        recommendations = []
        for raw in candidates:
            item = safe_node(raw)
            result = compare(focal, item)
            if result:
                recommendations.append({'target': item, 'score': result['score'],
                    'evidence': result['evidence'], 'status': 'algorithmic_hint_not_verified'})
        recommendations.sort(key=lambda x:(-x['score'], x['target']['id']))
        manual = [{'id': v['id'], 'target_id': v['target_id'], 'title': v['target_title'],
                   'kind': v['kind'], 'explanation': v['explanation'], 'author': v['author'],
                   'status': 'curator_claim_not_verified', 'direction': 'from' if v['from_id']==exhibit_id else 'to'}
                  for v in curated]
        return {'focus': focal, 'recommendations': recommendations[:limit], 'manual': manual,
                'sampled_candidates': len(candidates), 'notice': '分数仅表示元数据匹配程度，不是事实可信度、因果强度或馆藏真伪判断。人工关系是馆长陈述，未经独立核验。'}

    @app.get('/api/cosmos/me/map')
    def my_world_map(user=Depends(require_user)):
        with db() as c:
            rows = c.execute('''SELECT e.*,u.username owner FROM exhibits e JOIN users u ON e.user_id=u.id
                WHERE e.user_id=? ORDER BY e.created_at DESC,e.id DESC LIMIT ?''', (user['id'], MAX_RESULTS)).fetchall()
            count = c.execute('SELECT COUNT(*) FROM exhibits WHERE user_id=?',(user['id'],)).fetchone()[0]
            halls = [dict(x) for x in c.execute('SELECT id,name,visibility FROM halls WHERE user_id=? ORDER BY id LIMIT 60',(user['id'],)).fetchall()]
            hall_ids = {x['id'] for x in halls}
            memberships = [dict(x) for x in c.execute('''SELECT hi.exhibit_id,hi.hall_id FROM hall_items hi
                JOIN halls h ON h.id=hi.hall_id WHERE h.user_id=? ORDER BY hi.hall_id,hi.exhibit_id LIMIT 3000''', (user['id'],)).fetchall()]
            links = [dict(x) for x in c.execute('''SELECT from_id,to_id,kind,explanation FROM exhibit_links
                WHERE author_id=? ORDER BY created_at DESC LIMIT 400''', (user['id'],)).fetchall()]
        nodes = [safe_node(r) for r in rows]
        visible_ids = {n['id'] for n in nodes}
        domains = Counter(n['domain'] for n in nodes)
        groups = [{'id': key, 'count': v} for key,v in sorted(domains.items(),key=lambda x:(-x[1],x[0]))]
        edges = [{'from':m['from_id'],'to':m['to_id'],'kind':m['kind'],'explanation':m['explanation']}
                 for m in links if m['from_id'] in visible_ids and m['to_id'] in visible_ids]
        exhibit_halls = [{'exhibit_id':m['exhibit_id'],'hall_id':m['hall_id']}
                         for m in memberships if m['exhibit_id'] in visible_ids and m['hall_id'] in hall_ids]
        # The chart never exposes another person's private exhibit or name.
        return {'nodes': nodes, 'domains': groups, 'edges': edges, 'halls': halls,
                'memberships': exhibit_halls, 'total': count, 'visible_count': len(nodes),
                'sample_limit_per_era': 20, 'scope': 'private_to_signed_in_user',
                'notice': '这是你的私人收藏网络，不会因为查询而公开；按领域展示兴趣并列，而非推断人格。线条只表示你亲自提交的关联。'}